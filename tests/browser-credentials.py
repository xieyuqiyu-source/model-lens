"""Synthetic browser flows: MODEL_LENS_TEST_URL defaults to isolated dev port 1421."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

url = os.environ.get('MODEL_LENS_TEST_URL', 'http://127.0.0.1:1421')
fixture = Path(__file__).parent / 'fixtures/credentials-ipc.js'
with sync_playwright() as p:
    for engine in [p.webkit, p.chromium]:
        browser = engine.launch(headless=True)
        context = browser.new_context(viewport={'width': 1120, 'height': 760})
        context.add_init_script(path=fixture)
        page = context.new_page()
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto(url)
        stopped = page.locator('article').filter(has_text='stopped@example.invalid')
        expect(stopped).to_be_visible()
        refresh = stopped.get_by_role('button', name='刷新额度', exact=True)
        expect(refresh).to_be_enabled()
        refresh.click()
        expect(stopped.get_by_text('73% 剩余')).to_be_visible()
        expect(stopped.get_by_role('switch')).to_have_attribute('aria-checked', 'false')
        assert page.evaluate("__testCalls.every(c => c.cmd !== 'credential_toggle')")
        page.get_by_role('button', name='刷新全部额度', exact=True).click()
        expect(page.get_by_role('button', name='刷新全部额度', exact=True)).to_be_enabled()
        expect(page.get_by_role('button', name='删除 runtime@example.invalid')).to_be_disabled()
        delete = stopped.get_by_role('button', name='删除 stopped@example.invalid')
        delete.click()
        dialog = page.get_by_role('dialog')
        expect(dialog.get_by_text('stopped.json', exact=True)).to_be_visible()
        dialog.get_by_role('button', name='取消', exact=True).click()
        expect(dialog).to_have_count(0)
        assert page.evaluate("__testCalls.every(c => c.cmd !== 'credential_delete')")
        # Snapshot changed while confirmation was open: cannot submit old target.
        delete.click()
        page.evaluate("__testSnapshot.credentials[0].deleteToken = 'changed'; __testPublish()")
        expect(dialog.get_by_role('button', name='确认删除', exact=True)).to_be_disabled()
        dialog.get_by_role('button', name='关闭', exact=True).click()
        expect(dialog).to_have_count(0)
        delete.click()
        page.evaluate("__testNextError = '删除结果未确认，请刷新列表核实'; __testStale = true")
        dialog.get_by_role('button', name='确认删除', exact=True).click()
        expect(dialog.get_by_role('alert')).to_contain_text('删除结果未确认')
        expect(dialog.get_by_role('button', name='确认删除', exact=True)).to_be_disabled()
        dialog.get_by_role('button', name='关闭', exact=True).click()
        page.get_by_role('button', name='刷新凭证列表', exact=True).click()
        expect(delete).to_be_enabled()
        delete.click()
        dialog.get_by_role('button', name='确认删除', exact=True).click()
        expect(dialog).to_have_count(0)
        expect(stopped).to_have_count(0)
        # File import never displays the synthetic credential content in the DOM.
        import_trigger = page.get_by_role('button', name='导入 JSON', exact=True)
        import_trigger.focus()
        import_trigger.press('Enter')
        expect(page.get_by_role('dialog').get_by_role('button', name='关闭', exact=True)).to_be_focused()
        page.keyboard.press('Escape')
        expect(page.get_by_role('dialog')).to_have_count(0)
        expect(import_trigger).to_be_focused()
        import_trigger.click()
        page.get_by_label('选择 JSON 文件').set_input_files({'name':'oversize.json','mimeType':'application/json','buffer':b'x' * (1024 * 1024 + 1)})
        expect(dialog.get_by_role('alert')).to_contain_text('1 MiB')
        page.get_by_label('选择 JSON 文件').set_input_files({'name':'from-file.json','mimeType':'application/json','buffer':b'{"type":"codex","access_token":"synthetic-file-secret"}'})
        expect(dialog.get_by_text('已选择：', exact=False)).to_be_visible()
        assert 'synthetic-file-secret' not in page.inner_text('body')
        dialog.get_by_role('button', name='校验并导入', exact=True).click()
        expect(dialog.get_by_role('button', name='导入中…', exact=True)).to_be_disabled()
        expect(dialog).to_have_count(0)
        expect(page.locator('article').filter(has_text='from-file@example.invalid')).to_be_visible()
        page.get_by_role('button', name='导入 JSON', exact=True).click()
        expect(page.get_by_label('凭证 JSON')).to_have_value('')
        expect(page.get_by_label('凭证文件名')).to_have_count(0)
        page.get_by_label('选择 JSON 文件').set_input_files({'name':'from-file.json','mimeType':'application/json','buffer':b'{"type":"codex"}'})
        dialog.get_by_role('button', name='校验并导入', exact=True).click()
        expect(dialog.get_by_role('alert')).to_contain_text('同名')
        dialog.get_by_role('button', name='移除文件，改为粘贴').click()
        page.get_by_label('凭证 JSON').fill('broken')
        dialog.get_by_role('button', name='校验并导入', exact=True).click()
        expect(dialog.get_by_role('alert')).to_contain_text('JSON 格式无效')
        page.get_by_label('凭证 JSON').fill('{"type":"codex","email":"pasted@example.invalid","access_token":"synthetic-paste-secret"}')
        dialog.get_by_role('button', name='校验并导入', exact=True).click()
        expect(dialog).to_have_count(0)
        expect(page.locator('article').filter(has_text='pasted@example.invalid')).to_be_visible()
        assert page.evaluate("__testCalls.filter(c => c.cmd === 'credential_import').at(-1).args.name === ''")
        assert page.evaluate("!JSON.stringify(localStorage).includes('synthetic-')")
        assert not errors, errors
        if engine.name == 'webkit':
            page.screenshot(path='/tmp/modellens-credentials-main.png')
            page.get_by_role('button', name='导入 JSON', exact=True).click()
            expect(dialog).to_be_visible()
            page.wait_for_function("document.querySelector('dialog').getAnimations().every(a => a.playState === 'finished')")
            page.screenshot(path='/tmp/modellens-credentials-import.png')
            dialog.get_by_role('button', name='关闭', exact=True).click()
        # Compact window still allows disabled-account refresh.
        tray = context.new_page()
        tray.set_viewport_size({'width':400,'height':270})
        tray.on('pageerror', lambda error: errors.append(str(error)))
        tray.goto(url + '/?view=tray')
        refresh_tray = tray.get_by_role('button', name='刷新 stopped@example.invalid 额度', exact=True)
        expect(refresh_tray).to_be_enabled()
        refresh_tray.click()
        expect(tray.get_by_role('switch', name='stopped@example.invalid 凭证开关')).to_have_attribute('aria-checked', 'false')
        expect(refresh_tray).to_be_enabled()
        assert not errors, errors
        print(f'{engine.name}: 停用查询、文件/粘贴导入、冲突与错误、确认删除、外部变更、菜单栏通过')
        context.close()
        browser.close()
